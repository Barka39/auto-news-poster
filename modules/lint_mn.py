"""
Монгол хэлний автомат хяналт (S6): калька, буруу үг, англи бүтцийн ул мөрийг
постлохоос ӨМНӨ барина. Олдвол редакторын дамжлагад "ЗАС: ..." гэж буцаана;
дахин олдвол 1:1 солих боломжтойг нь кодоор солино.

Жагсаалт нь эзний өмнө анзаарсан бодит алдаанууд + prompt-д аль хэдийн
хориглосон хэллэгүүд. Шинэ алдаа олдох бүрд энд нэг мөр нэмнэ.
"""

import re

# (regex, тайлбар, 1:1 солих утга эсвэл None)
RULES = [
    (r"\bшүүгдс[эө]н\b", "'шүүгдсэн' = шүүхэд; тэмцээнээс 'хасагдсан'", "хасагдсан"),
    (r"\bагуулаг\w*", "'агуулаг' гэдэг үг байхгүй — 'ахлагч'", "ахлагч"),
    (r"\bшагналт\b", "'шагналт' биш 'шагналын эзэн'", "шагналын эзэн"),
    (r"самбараас бөмбөг авалт(ыг|ын|аар)?", "'самбараас бөмбөг авалт' → 'самбар'", "самбар"),
    (r"\bдамжуулалт өг(сөн|өв|лөө|ч)\b", "'дамжуулалт өгсөн' → 'дамжуулсан' / 'N дамжуулалттай'", None),
    (r"\bоноо (авсан|авав|авлаа) ч\b", "англи бүтэц 'scored X but' — 'X оноо авсан ч' зөв, харин давтагдвал өөрчил", None),
    (r"\bөнөөдрийн өнөөдөр\b", "давхардал", "өнөөдөр"),
    (r"\b(\w+)\s+\1\b", "ижил үг дараалан давтагдсан", None),
    (r"\bдвойл-дабл|дабл-дабл\b", "Латинаар: double-double", "double-double"),
    (r"\bтрипл-дабл\b", "Латинаар: triple-double", "triple-double"),
    (r"\bплей-офф\b", "Латинаар: playoff", "playoff"),
    (r"\bМакс(имальный|имум)\b", "орос үг", None),
    (r"\bкоманд(а|ын|ыг)\b", "'команд' биш 'баг'", None),
    (r"\bигрок\b", "орос үг — тоглогч", "тоглогч"),
    (r"\b(хийсэн|хийв|хийлээ) байна\b", "хоёр дахин өнгөрсөн цаг", None),
    (r"\bНаадам(ын|д)? тоглолт\b", "'наадам' биш 'тэмцээн/тоглолт'", None),
    (r"\bМэдээ ирлээ\b|\bСонирхолтой мэдээ\b|\bШинэ мэдээ:", "хоосон эхлэл", None),
    (r"\bОдоогоор мэдэгдэхгүй байна\b", "хоосон өгүүлбэр — эх баримтад байхгүй бол хас", None),
    (r"[A-Za-z]+[А-Яа-яӨөҮү]+|[А-Яа-яӨөҮү]+[A-Za-z]+", "нэг үгэнд Кирилл+Латин холилдсон (нэр хагас орчуулагдсан?)", None),
]

_COMPILED = [(re.compile(rx, re.IGNORECASE), why, fix) for rx, why, fix in RULES]

# Кирилл+Латин холимог дүрэмд зөвшөөрөгдөх: "NBA-ийн", "Lakers-т" маягийн дагавар
_SUFFIX_OK = re.compile(r"[A-Za-z]+-[А-Яа-яӨөҮү]+")


def check(text: str) -> list:
    """[(олдсон хэсэг, тайлбар, засвар|None), ...]"""
    hits = []
    for rx, why, fix in _COMPILED:
        for m in rx.finditer(text or ""):
            frag = m.group(0)
            if "холилдсон" in why:
                # "NBA-ийн" (зураастай дагавар) зөв; "Энцо Fernandez" маягийн зайтай бол энд баригдахгүй,
                # харин "Enzo-гийн" зөв тул зөвхөн зураасгүй нийлсэн үг л алдаа
                if "-" in frag or frag.isupper():
                    continue
            hits.append((frag, why, fix))
    return hits


def autofix(text: str) -> tuple:
    """1:1 засвартай алдааг солино. (шинэ_текст, солисон_тоо)"""
    n = 0
    for rx, why, fix in _COMPILED:
        if fix:
            text, k = rx.subn(fix, text)
            n += k
    return text, n


def report(hits: list) -> str:
    return "; ".join(f"«{frag}» — {why}" for frag, why, _ in hits[:6])
